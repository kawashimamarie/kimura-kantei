const blocks = [
  [-190,0,190,80],[-190,80,190,90],[-190,200,190,100],[-190,300,190,120],[-190,450,190,190],
  [0,0,90,80],[90,0,70,80],[160,0,80,80],[240,0,90,80],[0,80,120,90],[120,80,100,90],[220,80,110,90],
  [0,200,110,100],[110,200,100,100],[210,200,120,100],[0,300,80,120],[80,300,130,120],[210,300,120,120],
  [362,-60,130,120],[492,-60,120,120],[612,-60,150,120],[362,60,100,110],[462,60,140,110],[602,60,160,110],
  [502,200,110,120],[612,200,150,120],[362,320,110,100],[472,320,140,100],[612,320,150,100],
  [0,450,140,190],[140,450,190,190],[362,450,120,190],[482,450,150,190],[632,450,130,190],
  [-190,-110,280,80],[90,-110,240,80],[762,-60,200,230],[762,200,200,220],[762,450,200,190],[362,-170,400,80],
];
const target = [362,200,140,120];
let n = 0, o = [];
const num = () => { n++; return `${100 + ((n * 7) % 41)}-${(n % 5) + 1}`; };
o.push('<g class="mp-lots">');
for (const [x,y,w,h] of blocks) {
  o.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}"/>`);
}
o.push('</g><g class="mp-bld">');
blocks.forEach(([x,y,w,h], i) => {
  if (w > 185 || h > 185) { o.push(`<rect x="${x+18}" y="${y+20}" width="${Math.min(w-40,96)}" height="${Math.min(h-44,70)}"/>`); return; }
  const dx = 12 + (i * 5) % 9, dy = 12 + (i * 3) % 8;
  o.push(`<rect x="${x+dx}" y="${y+dy}" width="${w-dx-16-(i%3)*6}" height="${h-dy-18-(i%2)*8}"/>`);
});
o.push('</g><g class="mp-num">');
for (const [x,y,w,h] of blocks) { const t = num(); if (x >= -20 && w < 200) o.push(`<text x="${x+w-8}" y="${y+h-7}">${t}</text>`); }
o.push('</g>');
const [x,y,w,h] = target;
o.push(`<g class="mp-target"><rect class="tg-fill" x="${x}" y="${y}" width="${w}" height="${h}"/><rect class="tg-line" x="${x}" y="${y}" width="${w}" height="${h}"/>`);
for (const [px,py] of [[x,y],[x+w,y],[x+w,y+h],[x,y+h]]) o.push(`<rect class="tg-pin" x="${px-4.5}" y="${py-4.5}" width="9" height="9"/>`);
o.push('</g>');
console.log(o.join('\n'));
